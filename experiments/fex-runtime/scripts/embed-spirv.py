"""Embed validated build-time SPIR-V; the Android probe needs no shader files."""
import argparse
import hashlib
from pathlib import Path
import struct

parser = argparse.ArgumentParser()
parser.add_argument('vertex', type=Path)
parser.add_argument('fragment', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
lines = ['// Generated by embed-spirv.py; do not edit.', '#pragma once',
         '#include <cstdint>', 'namespace armxbox {']
for name, path in [('OutputVertexSpirv', args.vertex),
                   ('OutputFragmentSpirv', args.fragment)]:
    data = path.read_bytes()
    if not 20 <= len(data) <= 1024 * 1024 or len(data) % 4:
        raise SystemExit(f'{path.name}: invalid SPIR-V size')
    words = struct.unpack(f'<{len(data) // 4}I', data)
    if words[0] != 0x07230203:
        raise SystemExit(f'{path.name}: invalid SPIR-V magic')
    lines.append(f'// {path.name} SHA256 {hashlib.sha256(data).hexdigest()}')
    lines.append(f'inline constexpr uint32_t {name}[] = {{')
    for offset in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{word:08x}' for word in words[offset:offset + 8]) + ',')
    lines.append('};')
lines.extend(['} // namespace armxbox', ''])
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(lines))
